/**
 * Get popular banks sorted by prominence
 */
export function getPopularBanks(): VietnamBank[] {
  return POPULAR_BANK_CODES.map((code) =>
    VIETNAM_BANKS.find((b) => b.code === code)
  ).filter((b): b is VietnamBank => Boolean(b));
}

/**
 * Get other banks (non-popular) sorted alphabetically by shortName
 */
export function getOtherBanks(): VietnamBank[] {
  const popularSet = new Set(POPULAR_BANK_CODES);
  return VIETNAM_BANKS.filter((b) => !popularSet.has(b.code)).sort((a, b) =>
    a.shortName.localeCompare(b.shortName)
  );
}

/**
 * Find bank by Napas code, BIN, or shortName
 */
export function getBankByCode(query?: string | null): VietnamBank | undefined {
  if (!query) return undefined;
  const clean = query.trim().toUpperCase();

  return VIETNAM_BANKS.find(
    (b) =>
      b.code.toUpperCase() === clean ||
      b.bin === clean ||
      b.shortName.toUpperCase() === clean
  );
}
